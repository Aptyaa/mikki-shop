import type { ReactNode } from "react";
import { AppBar, Icon, IconButton } from "@mikki-shop/ui";

interface ScreenBarProps {
  title?: ReactNode;
  subtitle?: ReactNode;
  right?: ReactNode;
  /** Кнопка «назад» — своя, внутри шапки. Нативную у клиента не занимаем. */
  onBack?: () => void;
}

/**
 * Шапка экрана: `AppBar` из кита плюс своя кнопка «назад».
 *
 * **Нативную кнопку Telegram не занимаем.** До этого внутри клиента шапка
 * отдавала «назад» ему (`BackButton`), а свою прятала — ради одной кнопки
 * вместо двух. В живом клиенте это оказалось хуже: нативная кнопка живёт в
 * плавающей полосе поверх приложения и ведёт по истории браузера, а история у
 * нас растёт от переходов по вкладкам нижнего бара — то есть кнопка обещала
 * «назад по экранам», а делала «назад по вкладкам». Теперь клиент показывает
 * только «Закрыть», а навигация внутри приложения целиком наша: одна модель
 * поведения и в Telegram, и в браузере.
 *
 * **Маскота в шапке нет.** Голова, выглядывающая из-за названия раздела
 * (`013`), на телефоне читалась пятном: белая собака на кремовом фоне,
 * наполовину закрытая словом. Увеличение до 30px и наклон помягче не спасли —
 * решение владельца: снять до лучших времён, оставить заголовки текстом.
 * Компоновка `Logo variant="head"` и `AppBar titleBleed` в ките остались —
 * они рабочие и понадобятся, когда у маскота появится цветной вектор.
 */
export function ScreenBar({ title, subtitle, right, onBack }: ScreenBarProps) {
  return (
    <AppBar
      title={title}
      subtitle={subtitle}
      right={right}
      left={
        onBack && (
          <IconButton label="Назад" onClick={onBack}>
            <Icon name="chevron-left" />
          </IconButton>
        )
      }
    />
  );
}
